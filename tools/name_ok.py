"""마명·선수명이 **읽을 수 있는 상태인지** 판정한다. 🔴 판정을 한 곳에 둔다.

왜: 한국 KRA PDF 를 fitz 로 뽑으면 **글자 단위로** 깨진다.
  실측 2026-08-09 · 16경주 · 정상 한글 28,402자 ↔ 깨진 문자 **486자(1.7%)**
  경주당 18~35자. **어떤 마명이든 깨질 수 있다** — 이름 단위가 아니라 글자 단위다.
  실물: 부산 2R 8번이 `޷झ௏௏` 로 나왔다. 부산 1R 8번은 `히어로히트` 로 정상이었다.

🔴 쓰는 곳이 여럿이라 **여기 하나만 둔다**(목록 이중화 금지 · `tools/track_key.py` 선례).
  예상문 생성 · 배당판 마명 표시 · 로그가 같은 함수를 쓴다.
  ⚠ 대표 지시(2026-08-09): "배당판에 마명을 같이 쓰자" — 거기서도 같은 글자가 깨진다.

⚠ **일부만 정상인 이름을 반쯤 내보내지 않는다.** 하나라도 깨지면 통째로 버리고 마번만 쓴다.
🔴 근본 해결(별건 · 오늘 안 함): fitz 말고 다른 경로로 마명을 받는다.
  후보 — KRA 승인 20종 중 「출전표 상세정보」(15058677). 2026-08-05 확인 시점엔 미승인이었다.
"""
import re

# 🔴 실측(2026-08-09): 깨진 글자는 **아랍·데바나가리·타밀** 대역으로 떨어진다
#   부산 2R 8번 = U+07B7 · U+091D · U+0BCF.
#   ⚠ 처음엔 PUA(U+E000~)로 짐작했는데 **틀렸다** — 자기검증이 잡았다(원칙 17).
#   ⇒ 한글·영숫자·기본기호가 **아닌 문자**가 있으면 깨진 것으로 본다(화이트리스트).
_BAD = re.compile(u"[^가-힣ㄱ-ㆎ0-9A-Za-z 	()·,.\-'\"]")
_KO = re.compile(r"[가-힣]")


def name_broken(name):
    """깨진 글자가 하나라도 있으면 True."""
    return bool(_BAD.search(str(name or "")))


def safe_name(name, no=None):
    """읽을 수 있으면 이름을, 깨졌으면 `N번`(마번을 모르면 빈 문자열)을 돌려준다.
    ⚠ 마번은 정확하다 — 깨진 이름을 내보내는 것보다 마번만 쓰는 편이 낫다."""
    n = str(name or "").strip()
    if n and not name_broken(n) and _KO.search(n):
        return n
    return ("%s번" % no) if no is not None else ""


def label(no, name):
    """화면·문장용 라벨. 정상이면 `8번 히어로히트` · 깨졌으면 `8번`."""
    n = str(name or "").strip()
    if n and not name_broken(n) and _KO.search(n):
        return "%s번 %s" % (no, n)
    return "%s번" % no
